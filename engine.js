/* Pure finite-domain puzzle engine. No DOM, network, or persistence. */
(function (root) {
  "use strict";
  const BUILD_ID = "1.1.2"; // Generated by release.cjs.
  const SUPPORTED_SIZES = [5, 6, 7];
  const row = (x, size = 6) => Math.floor(x / size),
    col = (x, size = 6) => x % size;
  const indices = (length) => Array.from({ length }, (_, i) => i);
  function rng(seed) {
    let s = seed >>> 0;
    return () => {
      s += 0x6d2b79f5;
      let t = s;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function shuffle(a, random) {
    a = [...a];
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }
  function partition(random, N) {
    const minimum = N - 1,
      maximum = N === 5 ? 5 : N + 1;
    const rects = [[0, 0, N, N]],
      target = minimum + Math.floor(random() * (maximum - minimum + 1));
    while (rects.length < target) {
      const options = rects
        .map((q, i) => ({ q, i }))
        .filter(({ q }) => q[2] * q[3] > 2);
      const { q, i } = options[Math.floor(random() * options.length)];
      const [r, c, h, w] = q;
      const vertical = w > 1 && (h === 1 || random() < 0.5);
      const cut = 1 + Math.floor(random() * ((vertical ? w : h) - 1));
      rects.splice(
        i,
        1,
        vertical ? [r, c, h, cut] : [r, c, cut, w],
        vertical ? [r, c + cut, h, w - cut] : [r + cut, c, h - cut, w],
      );
    }
    const rooms = Array(N * N);
    shuffle(rects, random).forEach(([r, c, h, w], id) => {
      for (let y = r; y < r + h; y++)
        for (let x = c; x < c + w; x++) rooms[y * N + x] = id;
    });
    return rooms;
  }
  function nearRoom(cell, room, rooms, diagonal) {
    const N = Math.sqrt(rooms.length),
      row = (x) => Math.floor(x / N),
      col = (x) => x % N;
    return indices(rooms.length).some(
      (x) =>
        rooms[x] === room &&
        (diagonal
          ? Math.abs(row(x) - row(cell)) === 1 &&
            Math.abs(col(x) - col(cell)) === 1
          : Math.abs(row(x) - row(cell)) + Math.abs(col(x) - col(cell)) === 1),
    );
  }
  const OBJECT_TYPES = [
    "desk",
    "table",
    "fireplace",
    "chair",
    "piano",
    "billiards",
  ];
  const OBJECT_RELATIONS = [
    "sitting_on",
    "standing_on",
    "beside",
    "south_of",
    "avoids",
    "only_person",
  ];
  function fixturesValid(objects, rooms) {
    return (
      Array.isArray(objects) &&
      new Set(objects.map((o) => o.id)).size === objects.length &&
      new Set(objects.map((o) => o.cell)).size === objects.length &&
      objects.every(
        (o) =>
          OBJECT_TYPES.includes(o.type) &&
          o.id === o.type &&
          Number.isInteger(o.cell) &&
          o.cell >= 0 &&
          o.cell < rooms.length,
      )
    );
  }
  // only_person decomposes exactly into membership for the named person and
  // exclusion from that room for everyone else. All are forward unary deductions.
  function objectCandidate(clue, person, cell, rooms, objects) {
    const object = objects.find((o) => o.id === clue.object);
    if (!object || !OBJECT_RELATIONS.includes(clue.relation)) return false;
    if (clue.relation === "only_person")
      return person === clue.a
        ? rooms[cell] === rooms[object.cell]
        : rooms[cell] !== rooms[object.cell];
    if (person !== clue.a) return true;
    const N = Math.sqrt(rooms.length);
    switch (clue.relation) {
      case "sitting_on":
      case "standing_on":
        return cell === object.cell;
      case "beside":
        return (
          Math.abs(row(cell, N) - row(object.cell, N)) +
            Math.abs(col(cell, N) - col(object.cell, N)) ===
          1
        );
      case "south_of":
        return row(cell, N) > row(object.cell, N);
      case "avoids":
        return cell !== object.cell;
      default:
        return false;
    }
  }
  function placeObjects(solution, rooms, N, random) {
    const choose = (a) => a[Math.floor(random() * a.length)];
    const singles = indices(N).filter(
      (a) =>
        row(solution[a], N) < N - 1 &&
        solution.filter((x) => rooms[x] === rooms[solution[a]]).length === 1,
    );
    if (!singles.length) return null;
    const anchor = choose(singles),
      objects = [],
      available = [...OBJECT_TYPES];
    const affiliations = {
      desk: [0],
      table: [1, 6],
      fireplace: [1, 3],
      chair: [0, 3],
      piano: [3, 5],
      billiards: [4],
    };
    function add(cell) {
      const preferred = available.filter((type) =>
        affiliations[type].includes(rooms[cell]),
      );
      const type = choose(preferred.length ? preferred : available);
      available.splice(available.indexOf(type), 1);
      const object = { id: type, type, cell };
      objects.push(object);
      return object;
    }
    const on = add(solution[anchor]);
    const adjacentCells = indices(N * N).filter(
      (cell) =>
        cell !== on.cell &&
        solution.some(
          (x) =>
            Math.abs(row(x, N) - row(cell, N)) +
              Math.abs(col(x, N) - col(cell, N)) ===
            1,
        ),
    );
    const adjacent = add(choose(adjacentCells));
    const count = N - 1;
    while (objects.length < count)
      add(
        choose(
          indices(N * N).filter((cell) =>
            objects.every((o) => o.cell !== cell),
          ),
        ),
      );
    const besidePerson = choose(
      indices(N).filter(
        (a) =>
          Math.abs(row(solution[a], N) - row(adjacent.cell, N)) +
            Math.abs(col(solution[a], N) - col(adjacent.cell, N)) ===
          1,
      ),
    );
    const southPerson = choose(
      indices(N).filter((a) => row(solution[a], N) > row(on.cell, N)),
    );
    const avoidObject = choose(objects),
      avoidPerson = choose(
        indices(N).filter((a) => solution[a] !== avoidObject.cell),
      );
    const clue = (relation, a, object) => ({
      type: "object",
      relation,
      a,
      object: object.id,
    });
    const clues = [
      clue(random() < 0.5 ? "sitting_on" : "standing_on", anchor, on),
      clue("beside", besidePerson, adjacent),
      clue("south_of", southPerson, on),
      clue("avoids", avoidPerson, avoidObject),
      clue("only_person", anchor, on),
    ];
    return { objects, clues };
  }
  function unary(clue, cell, rooms) {
    if (clue.type === "room") return rooms[cell] === clue.room;
    if (clue.type === "beside" || clue.type === "touch")
      return nearRoom(cell, clue.room, rooms, clue.type === "touch");
    return true;
  }
  function direction(a, b, axis, N) {
    return axis === "north" ? row(a, N) < row(b, N) : col(a, N) < col(b, N);
  }
  function clueTrue(clue, positions, rooms, objects = []) {
    if (clue.type === "object") {
      if (!Number.isInteger(clue.a) || clue.a < 0 || clue.a >= positions.length)
        return false;
      if (!objectCandidate(clue, clue.a, positions[clue.a], rooms, objects))
        return false;
      if (clue.relation !== "only_person") return true;
      const object = objects.find((o) => o.id === clue.object);
      return (
        positions.filter((cell) => rooms[cell] === rooms[object.cell])
          .length === 1
      );
    }
    if (clue.type === "direction")
      return direction(
        positions[clue.a],
        positions[clue.b],
        clue.axis,
        Math.sqrt(rooms.length),
      );
    if (clue.type === "count")
      return (
        new Set(rooms).size - new Set(positions.map((x) => rooms[x])).size ===
        clue.count
      );
    return unary(clue, positions[clue.a], rooms);
  }
  function valid(positions, rooms, clues = [], objects = []) {
    const N = Math.sqrt(rooms.length);
    return (
      SUPPORTED_SIZES.includes(N) &&
      fixturesValid(objects, rooms) &&
      positions.length === N &&
      positions.every((x) => Number.isInteger(x) && x >= 0 && x < N * N) &&
      new Set(positions.map((x) => row(x, N))).size === N &&
      new Set(positions.map((x) => col(x, N))).size === N &&
      positions.filter((x) => rooms[x] === rooms[positions[0]]).length === 2 &&
      clues.every((c) => clueTrue(c, positions, rooms, objects))
    );
  }
  function initialDomains(puzzle, trace = null) {
    const N = puzzle.size ?? 6,
      cells = indices(N * N);
    return Array.from({ length: N }, (_, person) => {
      let domain = [...cells],
        previous = -1;
      puzzle.clues.forEach((clue, index) => {
        const next = domain.filter((cell) =>
          clue.type === "object"
            ? objectCandidate(
                clue,
                person,
                cell,
                puzzle.rooms,
                puzzle.objects ?? [],
              )
            : clue.a !== person ||
              clue.type === "direction" ||
              unary(clue, cell, puzzle.rooms),
        );
        if (next.length !== domain.length && trace) {
          trace.push({
            kind: "clue",
            person,
            clueIndices: [index],
            dependencies: previous < 0 ? [] : [previous],
            before: domain,
            after: next,
            removed: domain.length - next.length,
            removedCells: domain.filter((cell) => !next.includes(cell)),
          });
          previous = trace.length - 1;
        }
        domain = next;
      });
      return domain;
    });
  }
  function compatible(a, x, b, y, clues, N) {
    if (row(x, N) === row(y, N) || col(x, N) === col(y, N)) return false;
    return clues.every(
      (c) =>
        c.type !== "direction" ||
        ((c.a !== a || c.b !== b || direction(x, y, c.axis, N)) &&
          (c.a !== b || c.b !== a || direction(y, x, c.axis, N))),
    );
  }
  // Arc consistency removes unsupported candidates. This loop never guesses or branches.
  function propagate(puzzle) {
    const N = puzzle.size ?? 6;
    const trace = [],
      domains = initialDomains(puzzle, trace),
      lastChange = Array(N).fill(-1),
      causes = Array.from({ length: N }, () => new Set());
    trace.forEach((step, index) => {
      lastChange[step.person] = index;
      step.clueIndices.forEach((id) => causes[step.person].add(id));
    });
    let changed = true;
    while (changed) {
      changed = false;
      for (let a = 0; a < N; a++)
        for (let b = 0; b < N; b++)
          if (a !== b) {
            const next = domains[a].filter((x) =>
              domains[b].some((y) => compatible(a, x, b, y, puzzle.clues, N)),
            );
            if (next.length !== domains[a].length) {
              const pairClues = puzzle.clues.flatMap((clue, index) =>
                clue.type === "direction" &&
                ((clue.a === a && clue.b === b) ||
                  (clue.a === b && clue.b === a))
                  ? [index]
                  : [],
              );
              const clueIndices = pairClues.length ? pairClues : [...causes[b]];
              trace.push({
                kind: "arc",
                person: a,
                support: b,
                clueIndices,
                dependencies: [
                  ...new Set(
                    [lastChange[a], lastChange[b]].filter(
                      (index) => index >= 0,
                    ),
                  ),
                ],
                before: domains[a],
                after: next,
                supportDomain: [...domains[b]],
                removed: domains[a].length - next.length,
                removedCells: domains[a].filter((cell) => !next.includes(cell)),
              });
              lastChange[a] = trace.length - 1;
              causes[a] = new Set([...causes[a], ...causes[b], ...pairClues]);
              domains[a] = next;
              changed = true;
            }
          }
    }
    const solution = domains.map((d) => d[0]);
    return {
      domains,
      trace,
      solved:
        domains.every((d) => d.length === 1) &&
        valid(solution, puzzle.rooms, puzzle.clues, puzzle.objects),
      solution,
    };
  }
  // Exhaustive assignment search independent of propagation. Stop only after limit solutions.
  function enumerate(puzzle, limit = 2) {
    const N = puzzle.size ?? 6,
      row = (x) => Math.floor(x / N),
      col = (x) => x % N;
    const domains = initialDomains(puzzle),
      order = indices(N).sort((a, b) => domains[a].length - domains[b].length),
      positions = Array(N).fill(-1),
      solutions = [];
    function visit(depth, rows, cols) {
      if (solutions.length >= limit) return;
      if (depth === N) {
        if (valid(positions, puzzle.rooms, puzzle.clues, puzzle.objects))
          solutions.push([...positions]);
        return;
      }
      const a = order[depth];
      for (const x of domains[a]) {
        if (rows & (1 << row(x)) || cols & (1 << col(x))) continue;
        if (
          !positions.every(
            (y, b) => y < 0 || compatible(a, x, b, y, puzzle.clues, N),
          )
        )
          continue;
        positions[a] = x;
        visit(depth + 1, rows | (1 << row(x)), cols | (1 << col(x)));
        positions[a] = -1;
        if (solutions.length >= limit) return;
      }
    }
    visit(0, 0, 0);
    return solutions;
  }
  function verify(puzzle) {
    const deductions = propagate(puzzle),
      solutions = enumerate(puzzle);
    return {
      valid: valid(puzzle.solution, puzzle.rooms, puzzle.clues, puzzle.objects),
      unique:
        solutions.length === 1 &&
        solutions[0].every((x, i) => x === puzzle.solution[i]),
      forward:
        deductions.solved &&
        deductions.solution.every((x, i) => x === puzzle.solution[i]),
      deductions: deductions.trace.length,
    };
  }
  function generate(seed = Date.now() >>> 0, maxAttempts = 100, size = 6) {
    if (!SUPPORTED_SIZES.includes(size))
      throw new RangeError("UNSUPPORTED_SIZE");
    const N = size,
      row = (x) => Math.floor(x / N),
      col = (x) => x % N;
    const random = rng(seed);
    for (let attempt = 0; attempt < maxAttempts; attempt++) {
      const rooms = partition(random, N),
        columns = shuffle(indices(N), random);
      let solution = columns.map((c, r) => r * N + c);
      const pairs = solution.filter(
        (x) => solution.filter((y) => rooms[y] === rooms[x]).length === 2,
      );
      if (!pairs.length) continue;
      const victim = pairs[Math.floor(random() * pairs.length)];
      solution = [
        victim,
        ...shuffle(
          solution.filter((x) => x !== victim),
          random,
        ),
      ];
      const fixtures = placeObjects(solution, rooms, N, random);
      if (!fixtures) continue;
      const clues = solution.map((x, a) => ({
        type: "room",
        a,
        room: rooms[x],
      }));
      for (const axis of ["north", "west"]) {
        const order = indices(N).sort((a, b) =>
          axis === "north"
            ? row(solution[a]) - row(solution[b])
            : col(solution[a]) - col(solution[b]),
        );
        for (let i = 0; i < N - 1; i++)
          clues.push({ type: "direction", a: order[i], b: order[i + 1], axis });
      }
      for (const type of ["beside", "touch"]) {
        const choices = [];
        for (let a = 0; a < N; a++)
          for (const room of new Set(rooms))
            if (
              room !== rooms[solution[a]] &&
              nearRoom(solution[a], room, rooms, type === "touch")
            )
              choices.push({ type, a, room });
        if (choices.length)
          clues.push(choices[Math.floor(random() * choices.length)]);
      }
      clues.push({
        type: "count",
        count:
          new Set(rooms).size - new Set(solution.map((x) => rooms[x])).size,
      });
      clues.push(...fixtures.clues);
      const puzzle = {
        size,
        seed: seed >>> 0,
        rooms,
        solution,
        clues,
        objects: fixtures.objects,
      };
      // Keep room and vocabulary clues; remove redundant directional clues only when deduction still finishes.
      for (const clue of shuffle(
        clues.filter((c) => c.type === "direction"),
        random,
      )) {
        if (clues.filter((c) => c.type === "direction").length === 1) break;
        const index = clues.indexOf(clue);
        clues.splice(index, 1);
        if (!propagate(puzzle).solved) clues.splice(index, 0, clue);
      }
      const result = verify(puzzle);
      if (
        result.valid &&
        result.unique &&
        result.forward &&
        clues.some((c) => c.type === "beside") &&
        clues.some((c) => c.type === "touch")
      )
        return { ...puzzle, proof: result };
    }
    throw new Error("GENERATION_EXHAUSTED");
  }
  const API = {
    buildId: BUILD_ID,
    generate,
    verify,
    enumerate,
    propagate,
    valid,
    clueTrue,
    row,
    col,
    rng,
  };
  if (typeof module !== "undefined" && module.exports) module.exports = API;
  else root.MurdokuEngine = API;
})(typeof globalThis !== "undefined" ? globalThis : this);
