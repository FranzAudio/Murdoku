  function merge(english, translated) {
    if (Array.isArray(english))
      return english.map((entry, index) => merge(entry, translated?.[index]));
    if (english && typeof english === "object")
      return Object.fromEntries(
        [
          ...new Set([
            ...Object.keys(english),
            ...Object.keys(translated ?? {}),
          ]),
        ].map((key) => [key, merge(english[key], translated?.[key])]),
      );
    return typeof translated === "string" && translated.trim()
      ? translated
      : english;
  }
  function has(code) {
    return (
      Object.hasOwn(strings, code) &&
      !!strings[code] &&
      typeof strings[code] === "object" &&
      Object.keys(strings[code]).length > 0
    );
  }
  function locale(code) {
    return merge(strings.en, strings[code]);
  }
  function resolveString(path, code = "en") {
    const read = (table) =>
      path
        .replace(/\[(\d+)\]/g, ".$1")
        .split(".")
        .reduce((value, key) => value?.[key], table);
    const translated = read(strings[code]),
      english = read(strings.en);
    return typeof translated === "string" && translated.trim()
      ? translated
      : typeof english === "string" && english.trim()
        ? english
        : path;
  }
  function format(template, values = {}) {
    return String(template).replace(/\{(\w+)\}/g, (token, key) =>
      values[key] === undefined || values[key] === null
        ? token
        : String(values[key]),
    );
  }
  // Resolve the copy table's gender alternatives and Romance contractions
  // from the fixed character/room/object vocabulary, keeping dictionary text intact.
  function formatClue(template, values, code, context = {}) {
    if (code === "es" || code === "ca") {
      const female = [1, 4, 6].includes(context.person);
      template = template
        .replace("sentado/a", female ? "sentada" : "sentado")
        .replace("assegut/da", female ? "asseguda" : "assegut")
        .replace("dret/a", female ? "dreta" : "dret");
      if (context.object) {
        const feminine = (
          code === "es"
            ? ["table", "fireplace", "billiards"]
            : ["table", "fireplace", "chair", "billiards"]
        ).includes(context.object);
        const article =
          code === "ca" && context.object === "desk"
            ? "l’"
            : feminine
              ? "la "
              : "el ";
        template = template
          .replace(
            /\ba el\/la \{object\}/g,
            article === "el " ? "al {object}" : "a " + article + "{object}",
          )
          .replace(
            /\bde el\/la \{object\}/g,
            article === "el " ? "del {object}" : "de " + article + "{object}",
          )
          .replace(/el\/la \{object\}/g, article + "{object}");
      }
      if (Number.isInteger(context.room)) {
        const feminine = (
          code === "es" ? [0, 4, 6, 7] : [0, 3, 4, 5, 6]
        ).includes(context.room);
        if (code === "ca" && context.room === 2)
          template = template
            .replace(/a la \{room\}/g, "a l’{room}")
            .replace(/de la \{room\}/g, "de l’{room}");
        else if (!feminine)
          template = template
            .replace(/a la \{room\}/g, "al {room}")
            .replace(/de la \{room\}/g, "del {room}")
            .replace(/en la \{room\}/g, "en el {room}");
      }
    }
    return format(template, values);
  }
