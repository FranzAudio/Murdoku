(function (root) {
  "use strict";
  const BUILD_ID = "1.2.2"; // Generated by release.cjs.
  const E =
    typeof module !== "undefined" && module.exports
      ? require("./engine.js")
      : root.MurdokuEngine;
  class Game {
    constructor(puzzle) {
      this.puzzle = puzzle;
      this.size = puzzle.size ?? 6;
      this.positions = Array(this.size).fill(-1);
      this.marks = [];
      this.history = [];
      this.moves = 0;
      this.started = Date.now();
      this.hintProof = null;
      this.resetHints();
    }
    resetHints() {
      this.hintCursor = 0;
      this.currentHint = null;
    }
    // Only trace-derived domains are consulted. No hidden answer, placement,
    // mark, history, score, move count or timer is readjusted by this method.
    hint(advance = true) {
      if (!this.hintProof) this.hintProof = E.propagate(this.puzzle);
      const proof = this.hintProof,
        conflicts = this.conflicts();
      const bad = this.positions.flatMap((cell, person) =>
        cell >= 0 && !proof.domains[person].includes(cell) ? [cell] : [],
      );
      for (const cell of this.marks)
        if (
          proof.domains.some(
            (domain) => domain.length === 1 && domain[0] === cell,
          )
        )
          bad.push(cell);
      if (conflicts.rows.length || conflicts.cols.length || bad.length)
        return { status: "conflict", cells: [...new Set(bad)] };
      if (
        this.positions.every((cell) => cell >= 0) &&
        E.valid(
          this.positions,
          this.puzzle.rooms,
          this.puzzle.clues,
          this.puzzle.objects,
        )
      )
        return { status: "solved" };
      if (!proof.solved) return { status: "unavailable" };
      if (
        !advance &&
        this.currentHint &&
        (this.currentHint.status === "exhausted" ||
          this.positions[this.currentHint.step.person] < 0)
      )
        return this.currentHint;
      while (this.hintCursor < proof.trace.length) {
        const index = this.hintCursor++,
          step = proof.trace[index];
        if (this.positions[step.person] >= 0) continue;
        this.currentHint = {
          status: "step",
          step,
          index,
          total: proof.trace.length,
        };
        return this.currentHint;
      }
      return (this.currentHint = {
        status: "exhausted",
        total: proof.trace.length,
      });
    }
    save() {
      this.history.push({
        positions: [...this.positions],
        marks: [...this.marks],
      });
      this.moves++;
    }
    occupant(cell) {
      return this.positions.indexOf(cell);
    }
    act(cell, person, mark = false, clear = false) {
      if (!Number.isInteger(cell) || cell < 0 || cell >= this.size * this.size)
        return false;
      if (
        !mark &&
        !clear &&
        (!Number.isInteger(person) || person < 0 || person >= this.size)
      )
        return false;
      const occupant = this.occupant(cell);
      if (mark && occupant >= 0) return false;
      if (clear && occupant < 0 && !this.marks.includes(cell)) return false;
      if (!clear && !mark && occupant < 0 && person < 0) return false;
      this.save();
      if (occupant >= 0) this.positions[occupant] = -1;
      if (mark) {
        if (this.marks.includes(cell))
          this.marks = this.marks.filter((x) => x !== cell);
        else this.marks.push(cell);
      } else {
        this.marks = this.marks.filter((x) => x !== cell);
        if (!clear && occupant < 0) this.positions[person] = cell;
      }
      return true;
    }
    undo() {
      const previous = this.history.pop();
      if (!previous) return false;
      this.positions = previous.positions;
      this.marks = previous.marks;
      this.resetHints();
      return true;
    }
    reset() {
      this.resetHints();
      if (this.positions.some((x) => x >= 0) || this.marks.length) {
        this.save();
        this.positions.fill(-1);
        this.marks = [];
      }
    }
    conflicts() {
      const rows = [],
        cols = [];
      for (let i = 0; i < this.size; i++) {
        if (
          this.positions.filter((x) => x >= 0 && E.row(x, this.size) === i)
            .length > 1
        )
          rows.push(i);
        if (
          this.positions.filter((x) => x >= 0 && E.col(x, this.size) === i)
            .length > 1
        )
          cols.push(i);
      }
      return { rows, cols };
    }
    check() {
      const placed = this.positions.filter((x) => x >= 0).length,
        conflict = this.conflicts();
      const wrong = this.positions.filter(
        (x, i) => x >= 0 && x !== this.puzzle.solution[i],
      ).length;
      const contradicted = this.puzzle.clues.filter((c) => {
        if (c.type === "object" && c.relation === "only_person") {
          const object = this.puzzle.objects.find((o) => o.id === c.object);
          const room = this.puzzle.rooms[object.cell];
          return this.positions.some(
            (cell, person) =>
              cell >= 0 &&
              (person === c.a
                ? this.puzzle.rooms[cell] !== room
                : this.puzzle.rooms[cell] === room),
          );
        }
        if (c.type === "count" && placed < this.size) return false;
        if (c.a !== undefined && this.positions[c.a] < 0) return false;
        if (c.b !== undefined && this.positions[c.b] < 0) return false;
        return !E.clueTrue(
          c,
          this.positions,
          this.puzzle.rooms,
          this.puzzle.objects,
        );
      }).length;
      const solved =
        placed === this.size &&
        E.valid(
          this.positions,
          this.puzzle.rooms,
          this.puzzle.clues,
          this.puzzle.objects,
        );
      const murderer = solved
        ? this.positions.findIndex(
            (x, i) =>
              i > 0 &&
              this.puzzle.rooms[x] === this.puzzle.rooms[this.positions[0]],
          )
        : -1;
      return {
        missing: this.size - placed,
        wrong,
        clues: contradicted,
        conflicts: conflict.rows.length + conflict.cols.length,
        solved,
        murderer,
      };
    }
  }
  Game.buildId = BUILD_ID;
  if (typeof module !== "undefined" && module.exports) module.exports = Game;
  else root.MurdokuGame = Game;
})(typeof globalThis !== "undefined" ? globalThis : this);
